            MonFront[3] = MonFront[1];
            MonFront[4] = MonFront[0];
            MonFront[5] = new[] { new WalkTileDraw(new Rectangle(96, 96, 96, 96), new Point(0, 0), false) }; // SHP frame 9
            MonFront[6] = new[] { new WalkTileDraw(new Rectangle(192, 0, 96, 96), new Point(0, 0), false) }; // SHP frame 5
            MonFront[7] = MonFront[5];
            MonBack = new WalkTileDraw[BeatCountLocal][];
            MonBack[0] = new[] { new WalkTileDraw(new Rectangle(288, 0, 96, 96), new Point(0, 0), false) }; // SHP frame 4
            MonBack[1] = new[] { new WalkTileDraw(new Rectangle(192, 96, 96, 96), new Point(0, 0), false) }; // SHP frame 10
            MonBack[2] = new[] { new WalkTileDraw(new Rectangle(384, 0, 96, 96), new Point(0, 0), false) }; // SHP frame 7
            MonBack[3] = MonBack[1];
            MonBack[4] = MonBack[0];
            MonBack[5] = new[] { new WalkTileDraw(new Rectangle(288, 96, 96, 96), new Point(0, 0), false) }; // SHP frame 11
            MonBack[6] = new[] { new WalkTileDraw(new Rectangle(384, 288, 96, 96), new Point(0, 0), false) }; // SHP frame 24
            MonBack[7] = MonBack[5];

            CyokoFront = new WalkTileDraw[BeatCountLocal][];
            CyokoFront[0] = new[] { new WalkTileDraw(new Rectangle(400, 176, 48, 48), new Point(24, 0), false), new WalkTileDraw(new Rectangle(112, 64, 48, 32), new Point(6, 56), false), new WalkTileDraw(new Rectangle(480, 0, 16, 16), new Point(86, 54), false), new WalkTileDraw(new Rectangle(64, 64, 48, 32), new Point(6, 34), false), new WalkTileDraw(new Rectangle(432, 0, 32, 32), new Point(8, 8), false), new WalkTileDraw(new Rectangle(128, 128, 48, 32), new Point(28, 26), false) }; // SHP frame 9
